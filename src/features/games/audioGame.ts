export function shuffled<T>(values: readonly T[], random = Math.random): T[] {
  const result = [...values];

  for (let index = result.length - 1; index > 0; index -= 1) {
    const swapIndex = Math.floor(random() * (index + 1));
    [result[index], result[swapIndex]] = [result[swapIndex], result[index]];
  }

  return result;
}

export function createTuneGame(
  tunes: readonly Tune[] = TUNES,
  roundCount = 10,
  random = Math.random,
): Tune[] {
  return shuffled(tunes, random).slice(0, Math.min(roundCount, tunes.length));
}

export function createTuneOptions(
  answer: Tune,
  tunes: readonly Tune[] = TUNES,
  optionCount = 4,
  random = Math.random,
): Tune[] {
  const distractors = shuffled(
    tunes.filter((tune) => tune.file !== answer.file),
    random,
  ).slice(0, Math.max(0, optionCount - 1));

  return shuffled([answer, ...distractors], random);
}
